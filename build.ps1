# Builds SMLoader (winmm.dll) and the example mods.
#
#   .\build.ps1                      build into .\build
#   .\build.ps1 -Install             build and install into the game (game must be closed)
#   .\build.ps1 -Package             build and create release zips in .\dist
#   .\build.ps1 -GameDir "D:\Games\Steam\steamapps\common\Scrap Mechanic" -Install
#
# Needs Visual Studio 2022/2026 (or Build Tools) with "Desktop development with C++".
param(
    [switch]$Install,
    [switch]$Package,
    [string]$GameDir
)
$ErrorActionPreference = 'Stop'
$src = $PSScriptRoot
$out = Join-Path $src 'build'
New-Item -ItemType Directory -Force $out | Out-Null

$version = (Select-String -Path (Join-Path $src 'include\smloader.h') -Pattern '#define SMLOADER_VERSION\s+"([^"]+)"').Matches[0].Groups[1].Value

# --- MSVC environment ---------------------------------------------------------
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vsPath = $null
if (Test-Path $vswhere) { $vsPath = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath }
if (-not $vsPath) {
    $vsPath = Get-ChildItem "${env:ProgramFiles(x86)}\Microsoft Visual Studio\*\*", "$env:ProgramFiles\Microsoft Visual Studio\*\*" -Directory -ErrorAction SilentlyContinue |
        Where-Object { Test-Path "$($_.FullName)\VC\Auxiliary\Build\vcvars64.bat" } | Select-Object -First 1 -ExpandProperty FullName
}
if (-not $vsPath) { throw 'Visual Studio C++ build tools (x64) not found. Install "Desktop development with C++".' }
cmd /c "`"$vsPath\VC\Auxiliary\Build\vcvars64.bat`" >nul 2>&1 && set" | ForEach-Object {
    if ($_ -match '^([^=]+)=(.*)$') { Set-Item "env:$($Matches[1])" $Matches[2] }
}

# --- winmm forwarders ---------------------------------------------------------
# Every real winmm export is forwarded to System32 by absolute path, generated
# from the winmm.dll installed on this machine.
$sysWinmm = "$env:SystemRoot\System32\winmm.dll"
$lines = @('// Generated by build.ps1 from ' + $sysWinmm + ' - do not edit')
$target = '\\\\.\\GLOBALROOT\\SystemRoot\\System32\\winmm.dll'
foreach ($l in (dumpbin /nologo /exports $sysWinmm)) {
    if ($l -match '^\s+(\d+)\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]{8}\s+([A-Za-z_][\w@?$]*)') {
        $lines += "#pragma comment(linker, `"/export:$($Matches[2])=$target.$($Matches[2]),@$($Matches[1])`")"
    } elseif ($l -match '^\s+(\d+)\s+[0-9A-Fa-f]{8}\s+\[NONAME\]') {
        $lines += "#pragma comment(linker, `"/export:__winmm_ord$($Matches[1])=$target.#$($Matches[1]),@$($Matches[1]),NONAME`")"
    }
}
if ($lines.Count - 1 -lt 150) { throw "Only parsed $($lines.Count - 1) winmm exports from dumpbin; refusing to build a broken proxy." }
Set-Content -Encoding ascii (Join-Path $out 'forwards.inc') $lines
Write-Host "SMLoader $version - winmm forwarders: $($lines.Count - 1)"

# --- compile ------------------------------------------------------------------
$common = '/nologo', '/O2', '/MT', '/EHsc', '/std:c++17', '/W3', '/utf-8', '/DUNICODE', '/D_UNICODE', '/D_CRT_SECURE_NO_WARNINGS'
function Build-Dll($name, $sources, $extra = @()) {
    $objDir = Join-Path $out "obj\$name"
    New-Item -ItemType Directory -Force $objDir | Out-Null
    Push-Location $objDir   # objects land here; avoids /Fo"dir\" quoting trouble with spaces
    try {
        & cl @common @extra @sources /LD "/Fe$(Join-Path $out "$name.dll")" /link /NOLOGO user32.lib kernel32.lib
        if ($LASTEXITCODE -ne 0) { throw "build of $name failed" }
    } finally { Pop-Location }
}
Build-Dll 'winmm' @("$src\loader\loader.cpp") @("/I$out")
$examples = @()
foreach ($dir in Get-ChildItem (Join-Path $src 'examples') -Directory) {
    $sources = @(Get-ChildItem $dir.FullName -Filter *.cpp | ForEach-Object FullName)
    if ($sources.Count -eq 0) { continue }
    Build-Dll $dir.Name $sources @("/I$src\include")
    $examples += $dir.Name
}
Write-Host "Built: winmm.dll $($examples | ForEach-Object { "$_.dll" })"

# --- package ------------------------------------------------------------------
if ($Package) {
    $dist = Join-Path $src 'dist'
    $stage = Join-Path $dist 'stage'
    Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue
    # Player download: the loader only.
    $p = Join-Path $stage 'SMLoader'
    New-Item -ItemType Directory -Force (Join-Path $p 'Release'), (Join-Path $p 'SMLoader\mods') | Out-Null
    Copy-Item (Join-Path $out 'winmm.dll') (Join-Path $p 'Release')
    Copy-Item (Join-Path $src 'LICENSE') $p
    Copy-Item (Join-Path $src 'docs\INSTALL.txt') (Join-Path $p 'README.txt')
    Set-Content -Encoding ascii (Join-Path $p 'SMLoader\mods\Put mods here.txt') 'Put SMLoader mod DLLs in this folder.'
    $zip1 = Join-Path $dist "SMLoader-v$version.zip"
    Remove-Item $zip1 -ErrorAction SilentlyContinue
    Compress-Archive -Path (Join-Path $p '*') -DestinationPath $zip1
    # Modder download: example mods + tools.
    $d = Join-Path $stage 'devtools'
    New-Item -ItemType Directory -Force (Join-Path $d 'mods'), (Join-Path $d 'tools') | Out-Null
    foreach ($e in $examples) { Copy-Item (Join-Path $out "$e.dll") (Join-Path $d 'mods') }
    Copy-Item (Join-Path $src 'tools\smexec.ps1') (Join-Path $d 'tools')
    Copy-Item (Join-Path $src 'LICENSE') $d
    $zip2 = Join-Path $dist "SMLoader-devtools-v$version.zip"
    Remove-Item $zip2 -ErrorAction SilentlyContinue
    Compress-Archive -Path (Join-Path $d '*') -DestinationPath $zip2
    Remove-Item $stage -Recurse -Force
    Write-Host "Packaged: $zip1"
    Write-Host "          $zip2"
}

if (-not $Install) { return }

# --- install ------------------------------------------------------------------
if (-not $GameDir) {
    $candidates = @()
    $steam = (Get-ItemProperty 'HKCU:\Software\Valve\Steam' -ErrorAction SilentlyContinue).SteamPath
    if ($steam) {
        $candidates += Join-Path $steam 'steamapps\common\Scrap Mechanic'
        $vdf = Join-Path $steam 'steamapps\libraryfolders.vdf'
        if (Test-Path $vdf) {
            foreach ($m in (Select-String -Path $vdf -Pattern '"path"\s+"([^"]+)"').Matches) {
                $candidates += Join-Path ($m.Groups[1].Value -replace '\\\\', '\') 'steamapps\common\Scrap Mechanic'
            }
        }
    }
    $GameDir = $candidates | Where-Object { Test-Path (Join-Path $_ 'Release\ScrapMechanic.exe') } | Select-Object -First 1
    if (-not $GameDir) { throw 'Scrap Mechanic not found - pass -GameDir "<path to Scrap Mechanic>".' }
}
if (-not (Test-Path (Join-Path $GameDir 'Release\ScrapMechanic.exe'))) { throw "No Release\ScrapMechanic.exe in $GameDir" }
if (Get-Process ScrapMechanic -ErrorAction SilentlyContinue) { throw 'Close Scrap Mechanic before installing.' }
$mods = Join-Path $GameDir 'SMLoader\mods'
New-Item -ItemType Directory -Force $mods | Out-Null
Copy-Item (Join-Path $out 'winmm.dll') (Join-Path $GameDir 'Release') -Force
Write-Host "Installed loader: $(Join-Path $GameDir 'Release\winmm.dll')"
Write-Host "Example mods are in $out - copy the ones you want into $mods"
